# KTester ships Windows-only assumptions.  These are applied to a private copy.
LINUX_PATCHES: list[tuple[str, str, str]] = [
    (
        "preparation.py",
        '"-Djava.class.path=./Java/project-info-process.jar;./Java/project-index-builder.jar"',
        '"-Djava.class.path=./Java/project-info-process.jar:./Java/project-index-builder.jar"',
    ),
    (
        "generate_unit_test.py",
        '"-Djava.class.path=./Java/project-info-process.jar;./Java/project-index-builder.jar"',
        '"-Djava.class.path=./Java/project-info-process.jar:./Java/project-index-builder.jar"',
    ),
    (
        "procedure/workspace_preparation.py",
        'libs ="target/classes;"+ \';\'.join(lib_list)',
        'libs ="target/classes:"+ \':\'.join(lib_list)',
    ),
    (
        "tools/execute_test.py",
        'test_dependencies = f"libs/*;target/test-classes;target/classes;{self.dependency_fd}/*"',
        'test_dependencies = f"libs/*:target/test-classes:target/classes:{self.dependency_fd}/*"',
    ),
    # `subprocess.run(['cd', d, '&&', 'javac', ...], shell=True)` executes only
    # `cd` on POSIX. Run the compiler directly in the project directory instead.
    (
        "tools/execute_test.py",
        "        script = self.cd_cmd + compile_cmd\n"
        '        self.logger.info(" ".join(compile_cmd))\n'
        "        result = subprocess.run(script, capture_output=True, text=True, shell=True, encoding=\"utf-8\")",
        "        self.logger.info(\" \".join(compile_cmd))\n"
        "        result = subprocess.run(compile_cmd, cwd=self.cd_cmd[1], capture_output=True, text=True, encoding=\"utf-8\")",
    ),
]


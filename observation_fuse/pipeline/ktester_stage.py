def released_test_sources(source_module: Path, task: dict) -> list[Path]:
    """The KTester-generated test class(es) for this focal method."""
    return mb.discover_reference_tests(source_module, task)


def install_seed(
    seed_sources: list[Path], source_module: Path, build_dir: Path
) -> list[Path]:
    """Copy the seed test class into the isolated workspace."""
    installed = []
    for source in seed_sources:
        destination = build_dir / source.relative_to(source_module)
        destination.parent.mkdir(parents=True, exist_ok=True)
        # copyfile, not copy2: Maven must see a newer mtime than the scaffold
        # it replaces, otherwise it skips recompilation of the same FQN.
        shutil.copyfile(source, destination)
        installed.append(destination)
    return installed



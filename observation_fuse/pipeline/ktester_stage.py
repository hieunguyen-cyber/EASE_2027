"""Stage A -- obtain the KTester test class that seeds the fusion.

Two providers:

``artifact``
    Install the released KTester test class shipped with the dataset.  No LLM
    call, so a fusion run costs exactly one model's worth of tokens (Stage B).
    This is the default and is what the current observation exercises.

``generate``
    Re-run KTester's own pipeline against an OpenAI-compatible endpoint.  The
    KTester checkout is copied into the run root and patched for Linux before
    use, so the paper's repository is never modified.  This reproduces the
    approach rather than reusing its outputs, which matters when the seed must
    come from the same model as Stage B.
"""


@dataclass
class KTesterRuntime:
    """A patched, self-contained copy of KTester/code plus its knowledge index."""

    root: Path
    index_root: Path
    applied_patches: list[str]

    def activate(self) -> None:
        if str(self.root) not in sys.path:
            sys.path.insert(0, str(self.root))


def materialize_runtime(run_root: Path, force: bool = False) -> KTesterRuntime:
    """Copy KTester/code into the run root, apply the Linux fixes, wire the index."""
    runtime = run_root / "ktester_runtime"
    source = config.KTESTER_ROOT / "code"
    if not source.is_dir():
        raise SystemExit(f"Không tìm thấy KTester code: {source}")

    if force and runtime.exists():
        shutil.rmtree(runtime)
    applied: list[str] = []
    if not runtime.exists():
        shutil.copytree(
            source,
            runtime,
            ignore=shutil.ignore_patterns("__pycache__", "settings.py"),
        )
        for relative, old, new in LINUX_PATCHES:
            target = runtime / relative
            if not target.is_file():
                continue
            text = target.read_text(encoding="utf-8")
            if old not in text:
                # Already POSIX-clean, or upstream changed. Neither is an error,
                # but record it so a silent no-op is visible in the manifest.
                applied.append(f"SKIPPED {relative}: pattern not found")
                continue
            target.write_text(text.replace(old, new), encoding="utf-8")
            applied.append(f"patched {relative}")

    index_root = _assemble_index(run_root)
    return KTesterRuntime(root=runtime, index_root=index_root, applied_patches=applied)


def _assemble_index(run_root: Path) -> Path:
    """KTester expects json/, codegraph/ and lucene/ under one CODE_INFO_PATH."""
    index_root = run_root / "ktester_index"
    index_root.mkdir(parents=True, exist_ok=True)
    wanted = {
        "json": config.KTESTER_INDEX_JSON,
        "codegraph": config.KTESTER_INDEX_CODEGRAPH,
        "lucene": config.KTESTER_INDEX_LUCENE,
    }
    for name, source in wanted.items():
        link = index_root / name
        if link.is_symlink() or link.exists():
            continue
        if not source.is_dir():
            raise SystemExit(
                f"Thiếu index '{name}' cho Stage A generate: {source}\n"
                "Tải archive project_lucene của KTester hoặc chạy "
                "`python preparation.py -P` để dựng lại."
            )
        link.symlink_to(source.resolve())
    return index_root


def write_settings(
    runtime: KTesterRuntime,
    task_dir: Path,
    project_name: str,
    task_id: str,
    workspace: Path,
) -> Path:
    """Emit the settings.py that KTester's modules import at load time."""
    gen_root = task_dir / "ktester_stage"
    content = SETTINGS_TEMPLATE.format(
        dependency_path=str(runtime.root / "dependencies"),
        # KTester joins DATASET_PATH with each project-url, and reads
        # dataset_info.json from the same directory.
        dataset_path=str(config.PROJECTS_ROOT),
        code_info_path=str(runtime.index_root),
        baseline_path=str(gen_root / "baseline"),
        prompt_path=str(gen_root / "<project>/prompts"),
        fix_path=str(gen_root / "<project>/fix"),
        response_path=str(gen_root / "<project>/responses"),
        testclass_path=str(gen_root / "<project>/test_classes"),
        report_path=str(gen_root / "<project>/reports"),
        time_record_path=str(gen_root / "time"),
        model=config.KTESTER_LLM_MODEL,
        base_url=config.KTESTER_LLM_BASE_URL,
        api_key=config.KTESTER_LLM_API_KEY,
        temperature=config.KTESTER_LLM_TEMPERATURE,
        projects=[project_name],
        cases=[task_id],
        fix_tries=3,
    )
    settings_path = runtime.root / "settings.py"
    settings_path.write_text(content, encoding="utf-8")
    (gen_root).mkdir(parents=True, exist_ok=True)
    (gen_root / "settings_used.py").write_text(content, encoding="utf-8")
    return settings_path


def generate_seed(
    run_root: Path,
    task_dir: Path,
    project_name: str,
    task: dict,
    workspace: Path,
    build_dir: Path,
    maven: str,
    logs_dir: Path,
) -> list[Path]:
    """Run KTester's own generation pipeline for exactly one focal method.

    Returns the generated test source paths inside the workspace.
    """
    config.require_ktester_api_key()
    runtime = materialize_runtime(run_root)
    write_settings(runtime, task_dir, project_name, task["id"], workspace)

    # KTester's repair loop shells out to `javac -cp @dependencies.txt` and to
    # the JUnit console launcher, so the module needs a flat libs/ directory.
    mb.run_command(
        [maven, "-q", *mb.SKIP_FLAGS, "dependency:copy-dependencies",
         "-DoutputDirectory=libs"],
        build_dir,
        logs_dir / "a1_ktester_dependencies.log",
        "ktester-dependencies",
    )
    mb.run_command(
        [maven, "-q", *mb.SKIP_FLAGS, "-DskipTests", "compile"],
        build_dir,
        logs_dir / "a2_ktester_compile.log",
        "ktester-compile",
    )
    libs = sorted((build_dir / "libs").glob("*.jar"))
    classpath = ":".join(["target/classes"] + [f"libs/{jar.name}" for jar in libs])
    (build_dir / "dependencies.txt").write_text(classpath, encoding="utf-8")

    runtime.activate()
    import jpype  # imported here so `artifact` runs never need JPype installed

    jars = ":".join(
        str(runtime.root / "Java" / name)
        for name in ("project-info-process.jar", "project-index-builder.jar")
    )
    if not jpype.isJVMStarted():
        jpype.startJVM(jpype.getDefaultJVMPath(), "-Xmx4g", f"-Djava.class.path={jars}")

    dataset_info = mb.read_json(config.DATASET)
    # KTester resolves project paths as DATASET_PATH/<project-url>; point that
    # at the isolated workspace so generation never touches the shared dataset.
    scoped = {project_name: dict(dataset_info[project_name])}
    scoped[project_name]["project-url"] = str(build_dir)
    scoped[project_name]["focal-methods"] = [
        item for item in dataset_info[project_name]["focal-methods"]
        if item["id"] == task["id"]
    ]

    from settings import FileStructure as FS, TaskSettings as TS  # noqa: E402
    import procedure.generate_prompt as GenPrompt  # noqa: E402
    import procedure.generate_code as GenCode  # noqa: E402
    import procedure.post_process as Post  # noqa: E402

    _ensure_ktester_dirs(FS, project_name, task["id"])

    with mb.working_directory(runtime.root):
        GenPrompt.generate_init_prompts(FS, TS, scoped)
        GenPrompt.generate_test_case_prompts(FS, TS, scoped)
        GenCode.generate_testclass_framework(FS, TS, scoped)
        GenCode.generate_case_then_code(FS, TS, scoped)
        Post.verify_test_classes(FS, TS, scoped)

    produced = build_dir / task["test-path"]
    if not produced.is_file():
        raise RuntimeError(
            f"Stage A generate không tạo ra test class: {produced}. "
            f"Xem {task_dir / 'ktester_stage'}"
        )
    return [produced]


def _ensure_ktester_dirs(FS, project_name: str, task_id: str) -> None:
    for template in (FS.PROMPT_PATH, FS.FIX_PATH, FS.RESPONSE_PATH):
        Path(template.replace("<project>", project_name), task_id).mkdir(
            parents=True, exist_ok=True
        )
    for template in (FS.TESTCLASSS_PATH, FS.REPORT_PATH):
        Path(template.replace("<project>", project_name)).mkdir(
            parents=True, exist_ok=True
        )
    Path(FS.TESTCLASSS_PATH.replace("<project>", project_name), "temp").mkdir(
        parents=True, exist_ok=True
    )
